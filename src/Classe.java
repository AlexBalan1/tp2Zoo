/**
 * L'énumération Classe représente les différentes classes d'animaux présentes dans un zoo.
 */
public enum Classe {
    /**
     * Classe des poissons.
     */
    Poisson,
    /**
     * Classe des cétacés.
     */
    Cetace,
    /**
     * Classe des reptiles.
     */
    Reptile,
    /**
     * Classe des oiseaux.
     */
    Oiseau,
    /**
     * Classe des mammifères.
     */
    Mammifere
}
